<?php

use App\Http\Controllers\ArchiveController;
use App\Http\Controllers\BookController;
use App\Http\Controllers\CabinetController;
use App\Http\Controllers\DocumentController;
use App\Http\Controllers\DocumentRouteController;
use App\Http\Controllers\Documents\DocumentAttachmentController;
use App\Http\Controllers\Documents\DocumentAuditController;
use App\Http\Controllers\Documents\DocumentFieldsController;
use App\Http\Controllers\Documents\DocumentFileController;
use App\Http\Controllers\Documents\DocumentLinkController;
use App\Http\Controllers\Documents\DocumentLocationController;
use App\Http\Controllers\Documents\DocumentOcrController;
use App\Http\Controllers\Documents\DocumentOfficeActionController;
use App\Http\Controllers\Documents\DocumentWorkflowController;
use App\Http\Controllers\DocumentSearchController;
use App\Http\Controllers\DocumentTypeController;
use App\Http\Controllers\DrawerController;
use App\Http\Controllers\GlobalSearchController;
use Illuminate\Support\Facades\Route;

Route::redirect('/', '/dashboard')->name('home');

Route::middleware(['auth', 'verified'])->group(function () {
    Route::inertia('dashboard', 'dashboard/index')->name('dashboard');
    Route::get('documents', [DocumentController::class, 'index'])->name('documents.index');
    Route::get('documents/upload-options', [DocumentController::class, 'uploadOptions'])->name('documents.upload-options');
    Route::get('documents/office-actions', [DocumentOfficeActionController::class, 'index'])->name('documents.office-actions.index');
    Route::post('documents/office-actions/release', [DocumentOfficeActionController::class, 'release'])->name('documents.office-actions.release');
    Route::post('documents/office-actions/receive', [DocumentOfficeActionController::class, 'receive'])->name('documents.office-actions.receive');
    Route::post('documents/office-actions/revert', [DocumentOfficeActionController::class, 'revert'])->name('documents.office-actions.revert');
    Route::post('documents', [DocumentController::class, 'store'])->name('documents.store');
    Route::get('documents/search', DocumentSearchController::class)->name('documents.search');
    Route::get('search', GlobalSearchController::class)->name('system.search');
    Route::get('documents/declaration-numbers', [DocumentLinkController::class, 'index'])->name('documents.declaration-numbers');
    Route::get('documents/{document}/history', [DocumentLinkController::class, 'history'])->name('documents.history');
    Route::get('documents/{document}/audit', DocumentAuditController::class)->name('documents.audit');
    Route::get('documents/{document}/location', DocumentLocationController::class)->name('documents.location');
    Route::get('documents/{document}/workflow', [DocumentWorkflowController::class, 'show'])->name('documents.workflow.show');
    Route::patch('documents/{document}/status', [DocumentWorkflowController::class, 'update'])->name('documents.workflow.update');
    Route::post('documents/{document}/endorse', [DocumentWorkflowController::class, 'endorse'])->name('documents.workflow.endorse');
    Route::get('documents/{document}/ocr', [DocumentOcrController::class, 'show'])->name('documents.ocr');
    Route::patch('documents/{document}/ocr/review', [DocumentOcrController::class, 'review'])->name('documents.ocr.review');
    Route::patch('documents/{document}/ocr/regions/{region}', [DocumentOcrController::class, 'update'])->whereNumber('region')->name('documents.ocr.regions.update');
    Route::post('documents/{document}/ocr/retry', [DocumentOcrController::class, 'retry'])->name('documents.ocr.retry');
    Route::post('documents/{document}/map', [DocumentFieldsController::class, 'map'])->name('documents.map');
    Route::post('documents/{document}/title-suggestions', [DocumentFieldsController::class, 'suggestTitles'])->name('documents.title-suggestions');
    Route::put('documents/{document}/fields', [DocumentFieldsController::class, 'update'])->name('documents.fields');
    Route::post('documents/{document}/attachments', [DocumentAttachmentController::class, 'store'])->name('documents.attachments.store');
    Route::patch('documents/{document}/attachments/{attachment}', [DocumentAttachmentController::class, 'update'])->scopeBindings()->name('documents.attachments.update');
    Route::delete('documents/{document}/attachments/{attachment}', [DocumentAttachmentController::class, 'destroy'])->scopeBindings()->name('documents.attachments.destroy');
    Route::get('documents/{document}/ocr-pdf', [DocumentFileController::class, 'ocrPdf'])->name('documents.ocr-pdf');
    Route::get('documents/{document}/chain', [DocumentLinkController::class, 'show'])->name('documents.chain');
    Route::patch('documents/{document}', [DocumentLinkController::class, 'update'])->name('documents.update');
    Route::delete('documents/{document}', [DocumentController::class, 'destroy'])->name('documents.destroy');
    Route::get('documents/{document}/thumbnail', [DocumentFileController::class, 'thumbnail'])->name('documents.thumbnail');
    Route::get('documents/{document}/view', [DocumentFileController::class, 'view'])->name('documents.view');
    Route::get('archive', [ArchiveController::class, 'index'])->name('archive.index');
    Route::get('archive/books/{book}', [ArchiveController::class, 'book'])->name('archive.books.show');
    Route::get('archive/documents', [ArchiveController::class, 'locate'])->name('archive.documents.locate');
    Route::get('manage/cabinets', [CabinetController::class, 'index'])->name('manage.cabinets.index');
    Route::post('manage/cabinets', [CabinetController::class, 'store'])->name('manage.cabinets.store');
    Route::patch('manage/cabinets/{cabinet}', [CabinetController::class, 'update'])->name('manage.cabinets.update');
    Route::patch('manage/drawers/{drawer}', [DrawerController::class, 'update'])->name('manage.drawers.update');
    Route::post('manage/drawers/{drawer}/books', [BookController::class, 'store'])->name('manage.drawers.books.store');
    Route::get('manage/books', [BookController::class, 'index'])->name('manage.books.index');
    Route::get('manage/document-types', [DocumentTypeController::class, 'index'])->name('manage.document-types.index');
    Route::post('manage/document-types', [DocumentTypeController::class, 'store'])->name('manage.document-types.store');
    Route::patch('manage/document-types/{documentType}', [DocumentTypeController::class, 'update'])->name('manage.document-types.update');
    Route::get('manage/document-routes', [DocumentRouteController::class, 'index'])->name('manage.document-routes.index');
    Route::post('manage/document-routes', [DocumentRouteController::class, 'store'])->name('manage.document-routes.store');
    Route::patch('manage/document-routes/{documentRoute}', [DocumentRouteController::class, 'update'])->name('manage.document-routes.update');
    Route::get('manage/folders', [BookController::class, 'folders'])->name('manage.folders.index');
    Route::get('manage/lever-arch-files', [BookController::class, 'leverArchFiles'])->name('manage.lever-arch-files.index');
    Route::patch('manage/books/{book}', [BookController::class, 'update'])->name('manage.books.update');
    Route::redirect('archive/cabinets', '/manage/cabinets');
    Route::redirect('archive/books', '/manage/books');
    Route::redirect('filing-cabinets', '/archive');
});

require __DIR__.'/settings.php';
